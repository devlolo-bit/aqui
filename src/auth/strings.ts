const TABLES: Record<string, Table> = { en, 'pt-BR': ptBR, pt: ptBR, es, de, fr };

/** The table for a locale tag: the exact tag, then its language ("pt-PT" → pt), then English. */
export function tableFor(locale: string | undefined): Table {
  const tag = String(locale || 'en');
  return TABLES[tag] ?? TABLES[tag.split('-')[0].toLowerCase()] ?? en;
}

export function fill(text: string, vars: Record<string, string | number> = {}): string {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** `const t = useAuthText(); t("login.title")` — the words in the app's locale. */
export function useAuthText() {
  const table = tableFor(useLocale());
  return (key: AuthKey, vars?: Record<string, string | number>) => fill(table[key], vars);
}
